import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { pathToFileURL } from 'node:url'
import opentype from 'opentype.js'

/** A `weight` between two of the font's static instances is interpolated from them: both are
 *  instances of one variable font, so every glyph has the same points in each. */
export const WORDMARK = { text: 'ezdesign', weight: 550, tracking: -0.05 }

export const WORDMARK_MODULE = 'src/brand-wordmark.ts'

const EM = 100
const COORDS = ['x', 'y', 'x1', 'y1', 'x2', 'y2']

function loadGeist(weight) {
  const file = `@fontsource/geist-sans/files/geist-sans-latin-${weight}-normal.woff`
  const bytes = readFileSync(createRequire(import.meta.url).resolve(file))
  return opentype.parse(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength))
}

function outline({ text, weight, tracking }) {
  const [lo, hi] = [Math.floor(weight / 100) * 100, Math.ceil(weight / 100) * 100]
  const t = hi === lo ? 0 : (weight - lo) / (hi - lo)
  const mix = (a, b) => a + (b - a) * t
  const [light, heavy] = [loadGeist(lo), loadGeist(hi)]
  const heavyGlyphs = heavy.stringToGlyphs(text)
  const glyphs = light.stringToGlyphs(text).map((glyph, i) => [glyph, heavyGlyphs[i]])
  const path = new opentype.Path()
  let x = 0
  for (const [a, b] of glyphs) {
    const [pa, pb] = [a.getPath(x, 0, EM), b.getPath(x, 0, EM)]
    for (const [i, ca] of pa.commands.entries()) {
      const cb = pb.commands[i]
      if (cb?.type !== ca.type) throw new Error(`"${a.name}" differs in structure between ${lo} and ${hi}`)
      path.commands.push(Object.fromEntries(Object.entries(ca).map(([k, v]) => [k, COORDS.includes(k) ? mix(v, cb[k]) : v])))
    }
    x += (mix(a.advanceWidth, b.advanceWidth) * EM) / light.unitsPerEm + tracking * EM
  }
  const box = path.getBoundingBox()
  const tenth = (n, round) => round(n * 10) / 10
  const x1 = tenth(box.x1, Math.floor)
  const y1 = tenth(box.y1, Math.floor)
  return {
    d: path.toPathData(2).replace(/\d+\.\d+/g, (n) => String(Number(n))),
    viewBox: {
      x: x1,
      y: y1,
      width: tenth(tenth(box.x2, Math.ceil) - x1, Math.round),
      height: tenth(tenth(box.y2, Math.ceil) - y1, Math.round),
    },
  }
}

export function wordmarkModule(wordmark = WORDMARK) {
  const { d, viewBox } = outline(wordmark)
  const { x, y, width, height } = viewBox
  return `// Generated by \`npm run brand\` from scripts/brand-wordmark.mjs. Do not edit.

/** Geist ${wordmark.weight} at ${wordmark.tracking}em, outlined so no surface has to load the font.
 *  The viewBox is the ink bounds of a ${EM}-unit em, baseline at y=0. */
export const WORDMARK_VIEWBOX = { x: ${x}, y: ${y}, width: ${width}, height: ${height} }

export const WORDMARK_PATH =
  '${d}'
`
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(WORDMARK_MODULE, wordmarkModule())
  console.log(`wordmark ok (Geist ${WORDMARK.weight})`)
}
